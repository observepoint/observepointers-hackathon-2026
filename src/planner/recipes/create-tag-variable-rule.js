import { NAV, stepsToLibrary } from './_standards-library.js'
import { ruleNameFrom } from '../naming.js'

/**
 * Build a Tag & Variable Rule all the way through the conditions grid.
 *
 * HOW THIS DIFFERS FROM create_first_rule
 *
 * create_first_rule stops at the builder's first screen with the rule named, and says
 * so: "You set the conditions, since only you know which tags and values count as
 * right." That was the honest answer while the conditions grid was an unmapped
 * tag/variable matrix. It is still the right answer when the request is just "make me
 * a rule" — there is nothing to fill in from.
 *
 * This recipe is for the request that DOES say what correct looks like: "follow the
 * Timing Value best practice on Google Universal Analytics", "make sure utt, utc and
 * utv are set". Once a tag and a list of variables are named, every field in the grid
 * follows from them, and stopping early would leave the user in front of the hardest
 * screen in the app having been told the walkthrough was finished.
 *
 * THE SHAPE OF THE SCREEN, WHICH IS THE WHOLE REASON THIS IS BUILDABLE
 *
 * Two halves, and they are not symmetrical:
 *
 *   WHEN (optional)  A precondition. "Only evaluate this rule where the request is a
 *                    Google Universal Analytics hit whose t variable is 'timing'."
 *                    Without it the rule fails on every pageview that isn't a timing
 *                    beacon, which is a rule nobody wanted.
 *   EXPECT           What has to be true. One row per variable.
 *
 * Both halves render the same `rule-tag-variable-filter` grid, which is why the row
 * steps below are generated by one function used twice.
 *
 * WHY THE STEPS LEAN ON `>> last`
 *
 * Every variable row is an identical `input[formControlName="variable"]`. "Add
 * Variable, now fill it in" always means the row just added — the last one. See
 * content/selector-query.js. Without that this recipe would need an op-selector per
 * row index, generated upstream, and would break the moment a row was reordered.
 *
 * THREE STEPS THAT ONLY TALK
 *
 * Operator defaults to equals, Selector defaults to String, and REGEX is off. Those
 * are the right values here, so there is nothing to do — but a walkthrough that skips
 * silently past three columns leaves someone wondering what they were for, and this
 * is a screen people are afraid of. They carry `advance: 'continue'`, which is the one
 * thing the runtime cannot infer: an actor:'user' step that must NOT wait for a click,
 * because no click is coming.
 *
 * SELECTORS
 *   Added upstream — rule-when-add-variable, rule-expect-add-variable and the two
 *     account/status-code siblings. They were unaddressable: `.add-variable-btn` was
 *     on BOTH "Add Variable" and "Add Status Code", so any positional guess was one
 *     conditional block away from pointing at the wrong link.
 *   Angular's own — every grid cell has a formControlName, and `if-condition` /
 *     `then-condition` scope the two grids apart. No patch needed, and these are as
 *     stable as the form itself.
 *   Product vocabulary — "Tag", "is set", and the tag names come from constants
 *     (FilterTypes, TagVariableOperators, the tag catalogue), matched by label.
 *
 * SWEPT, on a live local moonbeam: everything down the WHEN half. The Create Rule
 * button, the name field, Next and Save; "Add condition"; Filter By and its "Tag"
 * option; the Operator that follows ("equals"); the tag autocomplete and
 * `mat-option.tag-id-option >> text=Google Universal Analytics`, which resolved to
 * "Google Universal AnalyticsWeb Analytics"; rule-when-add-variable and
 * rule-expect-add-variable, both reading "Add Variable"; and all five WHEN grid cells
 * including their `>> last` forms.
 *
 * SWEPT END TO END. Every step, across four passes, on a live local moonbeam.
 *
 * Two things the sweep settled that reading could not:
 *
 *   - `>> last` DISCRIMINATES, which a single-row grid could never have shown. Against
 *     three EXPECT rows it reported "matched 3 of 3" — so the operator is doing the
 *     work, not being quietly ignored while a plain selector happened to be right.
 *     `.grid-select-panel mat-option >> text=is set` reported "matched 9 of 13" and
 *     read "is set", and "is set" is the ninth entry in TagVariableOperators. Both
 *     halves of the selector language are now evidenced rather than assumed.
 *
 *   - `.mat-mdc-select-panel` is Material's class for EVERY select panel, so the
 *     Filter By scope also matches the grid's operator panel — a sweep with the grid
 *     dropdown open resolved it to "equals". Harmless: Material closes one overlay
 *     before opening another, so the two are never up together. Left alone
 *     deliberately rather than swapped for a `panelClass` added upstream, because the
 *     current selector is proven on a live page and the replacement would not be.
 *   - The tag option's visible text is the tag name WITH its category appended. That is
 *     why the contains fallback in selector-query.js has to stay: exact matching alone
 *     could never find a tag.
 */

const SELECTORS = {
  createRule: 'button[aria-label="Create Rule"]',
  name: 'rule-name-control input',
  // Only rendered while WHEN is empty; once a condition exists the button becomes
  // "Add precondition" inside if-conditions.
  addWhenCondition: 'button[aria-label="Add condition"]',
  filterBy: 'if-condition mat-select[formControlName="type"]',
  whenTag: 'if-condition input[formControlName="tagId"]',
  whenOperator: 'if-condition .main-filter mat-select[formControlName="matchType"]',
  addWhenVariable: '[op-selector="rule-when-add-variable"]',
  expectTag: 'then-condition input[formControlName="tagId"]',
  addExpectVariable: '[op-selector="rule-expect-add-variable"]',
  save: '[op-selector="rule-setup-save-btn"]',

  // OPTIONS ARE SCOPED TO THE PANEL THAT OWNS THEM, and a sweep is why.
  //
  // A bare `mat-option >> text=Tag` was checked while the TAG autocomplete happened to
  // be open, and resolved -- confidently -- to "Adobe DTMTag Management". Exact match
  // beats partial, but only among the elements offered; with no option reading exactly
  // "Tag" in that overlay it fell through to contains, and "DTMTag" contains it.
  //
  // Tightening the contains rule is not the fix. It has to stay, because the tag
  // options render their category inline -- the row for Google Universal Analytics
  // reads "Google Universal AnalyticsWeb Analytics" -- so exact matching alone would
  // never find a tag. The fix is to stop asking a question that spans two overlays.
  //
  // Material 22 gives every panel a type class, and this screen's grid supplies its
  // own `panelClass`, so both scopes are already there to be used.
  selectOption: '.mat-mdc-select-panel mat-option',
  gridOption: '.grid-select-panel mat-option',
}

/** The grid cells, scoped to whichever half of the screen they belong to. */
const cell = (half, name) =>
  `${half} rule-tag-variable-filter ${name === 'matchType' ? 'mat-select' : 'input'}[formControlName="${name}"]`

const DEFAULT_TAG = 'Google Universal Analytics'

/**
 * Parse "utt, utc and utv" — or a single name — into a list.
 *
 * Deliberately forgiving about the separators, because this arrives from a sentence
 * rather than a form. Deliberately strict about the contents: a variable name is a
 * token, so anything with a space in it is prose that leaked in and is dropped.
 */
function variableList(value) {
  if (Array.isArray(value)) return value.filter(Boolean)
  return String(value ?? '')
    .split(/\s*(?:,|\band\b|\/|\+)\s*/i)
    .map(v => v.trim().replace(/^['"]|['"]$/g, ''))
    .filter(v => v && !v.includes(' ') && v.length <= 32)
}

/**
 * One variable row: add it, name it, then three remarks about columns that are
 * already correct.
 *
 * THE STEP ORDER IS LOAD-BEARING, NOT STYLISTIC
 *
 * "Add Variable" carries `[class.disabled]="formData.invalid"`, and that class sets
 * `pointer-events: none`. So the link is genuinely unclickable until the row above it
 * is valid — you cannot add a second row before finishing the first. A walkthrough
 * that added all three rows and then filled them would point at an element the user
 * physically cannot click, and wait for a click that can never arrive.
 *
 * Hence: add, fill, SET THE OPERATOR, then add the next. The operator matters as much
 * as the name — a row defaults to "equals", which needs a value, so a row with only a
 * variable name in it is still invalid and still blocks the next one. "is set" is what
 * makes the EXPECT rows valid without one.
 *
 * `explain` is only true for the first row. The defaults are the same on every row,
 * and saying so four times is how a helpful walkthrough turns into a tedious one.
 */
function variableRowSteps({ half, addSelector, name, operator, value, explain }) {
  const steps = [
    {
      actor: 'user',
      targetSelector: addSelector,
      say: 'Add a variable row.',
      targetFallback: { description: 'the "Add Variable" link under the tag' },
      // The CLICK, not the row appearing. Visibility was already true from row two
      // onward -- the grid is on screen -- so this step resolved the instant it was
      // shown, never waited for the click, and the fill below then went into the row
      // that was already there. So utc overwrote utt.
      //
      // "A new row appeared" is not something a visibility test can say. The click is,
      // and it is the thing we are actually asking for.
      completion: { type: 'dom_event', value: 'click' },
    },
    {
      actor: 'ai',
      // The row that was just added, which is always the last one.
      targetSelector: `${cell(half, 'variable')} >> last`,
      say: `Setting the variable to "${name}".`,
      targetFallback: { description: 'the VARIABLE cell in the new row' },
      action: { type: 'fill_text', value: name },
      completion: { type: 'dom_event', value: 'input' },
    },
  ]

  if (explain) {
    steps.push({
      actor: 'user',
      targetSelector: `${half} rule-tag-variable-filter mat-checkbox[formControlName="variableMatchAsRegex"] >> last`,
      say: 'REGEX left off — the name is exact, not a pattern.',
      targetFallback: { description: 'the REGEX checkbox in this row' },
      // Nothing is going to happen here, so there is nothing to detect.
      advance: 'continue',
      completion: {
        type: 'dom_mutation',
        targetSelector: `${half} rule-tag-variable-filter mat-checkbox[formControlName="variableMatchAsRegex"]`,
      },
    })
  }

  if (operator) {
    steps.push({
      actor: 'user',
      targetSelector: `${cell(half, 'matchType')} >> last`,
      say: `Set OPERATOR to "${operator}".`,
      targetFallback: { description: 'the OPERATOR cell in this row' },
      completion: {
        type: 'dom_mutation',
        condition: 'visible',
        targetSelector: SELECTORS.gridOption,
      },
    })
    steps.push({
      actor: 'user',
      targetSelector: `${SELECTORS.gridOption} >> text=${operator}`,
      say: `Choose "${operator}".`,
      targetFallback: { description: `the "${operator}" option` },
      completion: { type: 'dom_event', value: 'click' },
    })
  } else if (explain) {
    steps.push({
      actor: 'user',
      targetSelector: `${cell(half, 'matchType')} >> last`,
      say: 'OPERATOR is already "equals", which is what we want.',
      targetFallback: { description: 'the OPERATOR cell in this row' },
      advance: 'continue',
      completion: { type: 'dom_mutation', targetSelector: cell(half, 'matchType') },
    })
  }

  if (value !== undefined) {
    if (explain) {
      steps.push({
        actor: 'user',
        targetSelector: `${cell(half, 'selectorType')} >> last`,
        say: 'SELECTOR is already "String" — we are matching the value itself.',
        targetFallback: { description: 'the SELECTOR cell in this row' },
        advance: 'continue',
        completion: { type: 'dom_mutation', targetSelector: cell(half, 'selectorType') },
      })
    }
    steps.push({
      actor: 'ai',
      targetSelector: `${cell(half, 'value')} >> last`,
      say: `Setting VALUE to "${value}".`,
      targetFallback: { description: 'the VALUE/VARIABLE cell in this row' },
      action: { type: 'fill_text', value },
      completion: { type: 'dom_event', value: 'input' },
    })
  }

  return steps
}

/** Pick a tag from an autocomplete: we type the search, the user picks the row. */
function tagSteps({ target, tagName, label, say }) {
  return [
    {
      actor: 'ai',
      targetSelector: target,
      say,
      targetFallback: { description: `the ${label} field` },
      action: { type: 'fill_text', value: tagName },
      completion: { type: 'dom_event', value: 'input' },
    },
    {
      actor: 'user',
      // By label, because the tag catalogue is the account's and the option shows
      // the tag's name above its category.
      targetSelector: `mat-option.tag-id-option >> text=${tagName}`,
      say: `Pick ${tagName} from the list.`,
      targetFallback: { description: `${tagName} in the tag list` },
      completion: { type: 'dom_event', value: 'click' },
    },
  ]
}

const numbered = steps => steps.map((step, i) => ({ ...step, id: `s${i + 1}` }))

export default {
  id: 'create_tag_variable_rule',
  title: 'Create a rule that checks variables on a tag',
  intent: {
    description:
      'Create a Tag & Variable Rule and fill in its conditions: which tag to look at, which ' +
      'variables have to be set, and the precondition that decides when the rule applies. Use ' +
      'when the request says what "correct" looks like — a named tag, named variables, or a ' +
      'named best practice. Use create_first_rule instead when it does not.',
    examples: [
      'make a rule that checks utt, utc and utv are set on Google Universal Analytics',
      'follow the Timing Value best practice on Google Analytics',
      'create a rule that validates our timing variables',
      'check that the timing beacons have all three timing variables set',
      'rule to make sure Adobe Analytics sets its campaign variables',
    ],
    keywords: [
      'timing value best practice',
      'timing value',
      'best practice rule',
      'rule that checks',
      'checks variables',
      'variables are set',
      'variable rule',
      'tag rules',
      'tag rule',
    ],
  },
  parameters: [
    {
      name: 'tagName',
      description: 'Which tag should this rule look at',
      required: false,
      default: DEFAULT_TAG,
    },
    {
      name: 'expectVariables',
      description: 'Which variables have to be set',
      required: false,
      // The Timing Value best practice, which is what "timing" in a request means:
      // utt, utc and utv are the three variables a Universal Analytics timing beacon
      // has to carry for the timing report to be usable.
      default: 'utt, utc, utv',
    },
    {
      name: 'whenVariable',
      description: 'Which variable identifies the requests this rule applies to',
      required: false,
      default: 't',
    },
    {
      name: 'whenValue',
      description: 'What that variable has to equal',
      required: false,
      default: 'timing',
    },
    {
      name: 'ruleName',
      description: 'A name for the rule',
      required: false,
      derive: ruleNameFrom,
    },
  ],

  buildSummary(context) {
    const tag = context.parameters?.tagName ?? DEFAULT_TAG
    const vars = variableList(context.parameters?.expectVariables)
    const when = context.parameters?.whenVariable
    const value = context.parameters?.whenValue

    const scope =
      when && value
        ? ` Only on requests where ${when}=${value}, so it doesn't fail on every other hit.`
        : ''

    return (
      `A rule says what "correct" means; the audit is what checks it. This one asks ${tag} to ` +
      `set ${vars.join(', ')}.${scope} The grid has six columns and three of them are already ` +
      "right — we'll say which as we go."
    )
  },

  buildSteps(context) {
    const tagName = context.parameters?.tagName ?? DEFAULT_TAG
    const expect = variableList(context.parameters?.expectVariables)
    const whenVariable = context.parameters?.whenVariable
    const whenValue = context.parameters?.whenValue
    const hasPrecondition = Boolean(whenVariable && whenValue)
    let explained = false

    const steps = [
      ...stepsToLibrary({
        link: NAV.rulesLink,
        label: 'Tag & Variable Rules',
        route: '/rules/library',
      }).map(({ id: _id, ...step }) => step),
      {
        actor: 'user',
        targetSelector: SELECTORS.createRule,
        say: 'Start a new rule.',
        targetFallback: { description: 'the "Create Rule" button' },
        completion: { type: 'dom_mutation', condition: 'visible', targetSelector: SELECTORS.name },
      },
      {
        actor: 'ai',
        targetSelector: SELECTORS.name,
        say: 'Naming it "{{parameters.ruleName}}".',
        targetFallback: { description: 'the rule name field at the top of the builder' },
        action: { type: 'fill_text', value: '{{parameters.ruleName}}' },
        completion: { type: 'dom_event', value: 'change' },
      },
    ]

    if (hasPrecondition) {
      steps.push(
        {
          actor: 'user',
          targetSelector: SELECTORS.addWhenCondition,
          say: 'Add a WHEN condition — it decides where this rule applies.',
          targetFallback: { description: 'the "Add condition" button under WHEN' },
          completion: {
            type: 'dom_mutation',
            condition: 'visible',
            targetSelector: SELECTORS.filterBy,
          },
        },
        {
          actor: 'user',
          targetSelector: SELECTORS.filterBy,
          say: 'Open Filter By.',
          targetFallback: { description: 'the "Filter By" dropdown' },
          completion: {
            type: 'dom_mutation',
            condition: 'visible',
            targetSelector: SELECTORS.selectOption,
          },
        },
        {
          actor: 'user',
          targetSelector: `${SELECTORS.selectOption} >> text=Tag`,
          say: 'Choose "Tag".',
          targetFallback: { description: 'the "Tag" option' },
          completion: { type: 'dom_event', value: 'click' },
        },
        {
          actor: 'user',
          targetSelector: SELECTORS.whenOperator,
          say: 'Operator is already "equals" — the only one Tag offers.',
          targetFallback: { description: 'the Operator dropdown next to Filter By' },
          advance: 'continue',
          completion: { type: 'dom_mutation', targetSelector: SELECTORS.whenOperator },
        },
        ...tagSteps({
          target: SELECTORS.whenTag,
          tagName,
          label: 'Value',
          say: `Searching tags for "${tagName}".`,
        }),
        ...variableRowSteps({
          half: 'if-condition',
          addSelector: SELECTORS.addWhenVariable,
          name: whenVariable,
          value: whenValue,
          explain: true,
        }),
      )
      // The columns mean the same thing in both grids, so explaining them a second
      // time under EXPECT is padding.
      explained = true
    }

    // EXPECT has its own Select Tag — the WHEN half is a filter, not a subject — so
    // the same tag gets named twice. The copy says why, because otherwise it reads
    // like the walkthrough lost its place.
    steps.push(
      ...tagSteps({
        target: SELECTORS.expectTag,
        tagName,
        label: 'Select Tag under EXPECT',
        say: hasPrecondition
          ? `Now EXPECT: the same tag again, this time as the subject.`
          : `Searching tags for "${tagName}".`,
      }),
    )

    // "is set" rather than equals: the best practice is that the variables are
    // PRESENT. Pinning their values would fail on every page with a different
    // timing number, which is every page.
    expect.forEach((name, index) => {
      steps.push(
        ...variableRowSteps({
          half: 'then-condition',
          addSelector: SELECTORS.addExpectVariable,
          name,
          operator: 'is set',
          explain: index === 0 && !explained,
        }),
      )
    })

    steps.push({
      actor: 'user',
      targetSelector: SELECTORS.save,
      say: "Save it. It's now attachable to any audit under Standards.",
      targetFallback: { description: 'the Save button in the rule builder' },
      // Waits for the MODAL TO CLOSE, not for the click.
      //
      // This is why the next walkthrough could not find what this one made. Advancing on
      // the click meant the run navigated away while the save was still in flight, and
      // the audit editor's Standards picker then read a library that genuinely did not
      // contain it yet. The modal closing is the app's own confirmation that the save
      // landed, and it is the only signal available from outside.
      //
      // Same lesson as the OneTrust sync banner, applied one screen later than it should
      // have been: a Save whose result something downstream depends on has to wait for
      // the save, not for the button.
      completion: {
        type: 'dom_mutation',
        condition: 'hidden',
        targetSelector: SELECTORS.name,
      },
    })

    return numbered(steps)
  },
}
